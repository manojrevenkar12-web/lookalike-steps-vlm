def _gate_table(lines: list[dict]) -> list[str]:
    out = ["| Line | Value | Limit | |", "|---|---:|---:|---|"]
    for x in lines:
        v = x["value"]
        vs = "n/a" if v is None else (f"{v:.4g}" if isinstance(v, float) else str(v))
        out.append(f"| {x['line']} | {vs} | {x['op']} {x['limit']} | {'pass' if x['ok'] else '**fail**'} |")
    return out


