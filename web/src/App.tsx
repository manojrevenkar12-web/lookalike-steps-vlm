import { Conditions } from "./features/conditions/Conditions";
import { Designs } from "./features/designs/Designs";
import { EdgePanel } from "./features/edge/EdgePanel";
import { Hands } from "./features/hands/Hands";
import { Hero } from "./features/hero/Hero";
import { Timeline } from "./features/timeline/Timeline";
import { useReport } from "./shared/data/useReport";
import { EmptyState, ErrorState, Skeleton } from "./shared/ui/States";
import styles from "./app.module.css";

export function App() {
  const { state, retry } = useReport();
  return (
    <main className={styles.page}>
      {state.status === "loading" && <Skeleton rows={6} />}
      {state.status === "error" && <ErrorState message={state.message} onRetry={retry} />}
      {state.status === "empty" && <EmptyState />}
      {state.status === "ready" && (
        <>
          <Hero report={state.report} />
          <Timeline report={state.report} />
          <Designs report={state.report} />
          <Conditions report={state.report} />
          <Hands report={state.report} />
          <EdgePanel report={state.report} />
          <footer className={styles.footer}>
            Simulated stations, exact truth. Numbers from reports/{state.report.label}.json, generated by the evaluation.
          </footer>
        </>
      )}
    </main>
  );
}
